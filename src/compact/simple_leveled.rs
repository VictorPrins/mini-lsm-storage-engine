use serde::{Deserialize, Serialize};

use crate::lsm_storage::LsmStorageState;

#[derive(Debug, Clone)]
pub struct SimpleLeveledCompactionOptions {
    pub size_ratio_percent: usize,
    pub level0_file_num_compaction_trigger: usize,
    pub max_levels: usize,
}

#[derive(Debug, Serialize, Deserialize)]
pub struct SimpleLeveledCompactionTask {
    // if upper_level is `None`, then it is L0 compaction
    pub upper_level: Option<usize>,
    pub upper_level_sst_ids: Vec<usize>,
    pub lower_level: usize,
    pub lower_level_sst_ids: Vec<usize>,
    pub is_lower_level_bottom_level: bool,
}

pub struct SimpleLeveledCompactionController {
    options: SimpleLeveledCompactionOptions,
}

impl SimpleLeveledCompactionController {
    pub fn new(options: SimpleLeveledCompactionOptions) -> Self {
        Self { options }
    }

    /// Generates a compaction task.
    ///
    /// Returns `None` if no compaction needs to be scheduled. The order of SSTs in the compaction task id vector matters.
    pub fn generate_compaction_task(
        &self,
        snapshot: &LsmStorageState,
    ) -> Option<SimpleLeveledCompactionTask> {
        if snapshot.l0_sstables.len() >= self.options.level0_file_num_compaction_trigger {
            let lower_level = 1;
            return Some(SimpleLeveledCompactionTask {
                upper_level: None, // None means L0
                upper_level_sst_ids: snapshot.l0_sstables.clone(),
                lower_level,
                lower_level_sst_ids: snapshot.levels[lvl_to_idx(lower_level)].1.clone(),
                is_lower_level_bottom_level: self.options.max_levels == lower_level,
            });
        }

        // loop over layer L2 ... Ln
        for level in 2..(self.options.max_levels + 1) {
            // convert from layer to index: layer i has index i-1
            let upper_level_size = snapshot.levels[lvl_to_idx(level - 1)].1.len();

            if upper_level_size == 0 {
                continue;
            }

            let lower_level_size = snapshot.levels[lvl_to_idx(level)].1.len();

            if (lower_level_size * 100) / upper_level_size < self.options.size_ratio_percent {
                return Some(SimpleLeveledCompactionTask {
                    upper_level: Some(level - 1),
                    upper_level_sst_ids: snapshot.levels[lvl_to_idx(level - 1)].1.clone(),
                    lower_level: level,
                    lower_level_sst_ids: snapshot.levels[lvl_to_idx(level)].1.clone(),
                    is_lower_level_bottom_level: self.options.max_levels == level,
                });
            }
        }

        None
    }

    /// Apply the compaction result.
    ///
    /// The compactor will call this function with the compaction task and the list of SST ids generated by compact(). This function applies the
    /// result and generates a new LSM state. The functions should only change `l0_sstables` and `levels` without changing memtables
    /// and `sstables` hash map. Though there should only be one thread running compaction jobs, you should think about the case
    /// where an L0 SST gets flushed while the compactor generates new SSTs, and with that in mind, you should do some sanity checks
    /// in your implementation.
    ///
    /// The function returns the new state, and the SST ids that can be removed from disk.
    /// It is the responsible of the caller to lock the state appropriately around this method call.
    pub fn apply_compaction_result(
        &self,
        snapshot: &LsmStorageState,
        task: &SimpleLeveledCompactionTask,
        new_sst_ids: &[usize],
    ) -> (LsmStorageState, Vec<usize>) {
        let mut state = LsmStorageState::clone(snapshot);

        let upper_level = match task.upper_level {
            Some(lvl) => &mut state.levels[lvl_to_idx(lvl)].1,
            None => &mut state.l0_sstables,
        };

        // Remove the SSTs that were compacted
        upper_level.retain(|id| !task.upper_level_sst_ids.contains(id));

        let lower_level = &mut state.levels[lvl_to_idx(task.lower_level)].1;

        // Remove the SSTs that were compacted
        lower_level.retain(|id| !task.lower_level_sst_ids.contains(id));

        // add the new SSTs produced by compaction
        lower_level.extend(new_sst_ids);

        let mut ssts_to_remove = Vec::clone(&task.upper_level_sst_ids);
        ssts_to_remove.extend(&task.lower_level_sst_ids);

        (state, ssts_to_remove)
    }
}

fn lvl_to_idx(level: usize) -> usize {
    level - 1
}
